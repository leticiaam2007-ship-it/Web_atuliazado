<h1>Resolução da questão 2 </h1>

<h2>O PHP é executado no navegador assim como o JavaScript?</h2>

<h3>Não. O PHP funciona de maneira diferente do JavaScript.
     Enquanto o JavaScript é executado diretamente no navegador do usuário, o 
     PHP é executado no servidor. Isso significa que, quando 
     uma página em PHP é acessada, o servidor processa todo o código e
      envia ao navegador apenas o resultado, normalmente em HTML. Por isso, 
      o usuário não consegue ver o código PHP, apenas o conteúdo que ele gerou.
    </h3>
    
